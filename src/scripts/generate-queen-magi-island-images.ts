export const QUEEN_MAGI_ISLAND_IMAGE_PLANS: readonly IslandImagePlan[] = [PARADISE_PLAN, HULA_HULA_PLAN];

export function validateIslandImagePlan(): string[] {
  const errors: string[] = [];
  if (QUEEN_MAGI_ISLAND_IMAGE_PLANS.length !== 2) errors.push('The plan must target both island sites.');
  if (!/no text/i.test(STYLE) || !/no logos/i.test(STYLE) || !/do not imitate/i.test(STYLE)
    || !/do not depict or reproduce/i.test(STYLE) || !/not identifiable/i.test(STYLE)) {
    errors.push('The generated-only, no-brand and no-person prompt guard is missing.');
  }

  const tenantSlugs = new Set<string>();
  for (const plan of QUEEN_MAGI_ISLAND_IMAGE_PLANS) {
    if (tenantSlugs.has(plan.tenantSlug)) errors.push(`Duplicate plan: ${plan.tenantSlug}`);
    tenantSlugs.add(plan.tenantSlug);
    if (!plan.urlMarker.includes(plan.tenantSlug)) errors.push(`The asset path must be scoped to the site: ${plan.tenantSlug}`);
    if (plan.folder !== `tours/${plan.tenantSlug}/generated` || plan.urlMarker !== `/attractions-network/${plan.folder}/`) {
      errors.push(`Generated frames must live in their own folder, apart from the real photographs: ${plan.tenantSlug}`);
    }
    if (plan.heroScenes.length < 3 || plan.heroScenes.length > 4) errors.push(`Between three and four site header scenes are required: ${plan.tenantSlug}`);
    if (plan.heroTarget < plan.heroScenes.length) errors.push(`Header target is below the number of scenes: ${plan.tenantSlug}`);
    for (const scene of plan.heroScenes) {
      if (scene.trim().length < 80) errors.push(`Header scene is too thin: ${plan.tenantSlug}`);
      if (sceneNeedsQualifier(scene)) errors.push(`Header scene depicts something brandable without a generic qualifier: ${plan.tenantSlug}`);
      if (NAMES_A_REAL_PLACE.test(scene)) errors.push(`Header scene names a real venue or operator: ${plan.tenantSlug}`);
    }

    const tourSlugs = new Set<string>();
    for (const tour of plan.tours) {
      if (tourSlugs.has(tour.slug)) errors.push(`Duplicate image target: ${tour.slug}`);
      tourSlugs.add(tour.slug);
      // Real photographs are mirrored into tours/<site>/<tour>/, so a tour named after the folder would blur the line.
      if (tour.slug === 'generated') errors.push(`A tour slug may not share the generated folder name: ${plan.tenantSlug}`);
      if (!tour.scenes.length || tour.scenes.length > IMAGES_PER_TOUR) errors.push(`Between one and ${IMAGES_PER_TOUR} scenes are required: ${tour.slug}`);
      for (const scene of tour.scenes) {
        if (scene.trim().length < 80) errors.push(`Scene is too thin: ${tour.slug}`);
        if (sceneNeedsQualifier(scene)) errors.push(`Scene depicts something brandable without a generic qualifier: ${tour.slug}`);
        if (NAMES_A_REAL_PLACE.test(scene)) errors.push(`Scene names a real venue or operator: ${tour.slug}`);
        if (!imageAltSchema.safeParse(illustrativeAlt(scene)).success) errors.push(`Scene cannot be described as an illustration: ${tour.slug}`);
      }
      // A site's tours may never be filled from the other site's plan.
      const otherPrefix = plan.tenantSlug === 'hula-hula-island' ? 'paradise-' : 'hula-hula-';
      if (tour.slug.startsWith(otherPrefix)) errors.push(`Target belongs to the other site: ${tour.slug}`);
    }

    const pageSlugs = new Set<string>();
    for (const facility of plan.facilities) {
      if (pageSlugs.has(facility.slug)) errors.push(`Duplicate page target: ${facility.slug}`);
      pageSlugs.add(facility.slug);
      if (facility.scene.trim().length < 80) errors.push(`Page scene is too thin: ${facility.slug}`);
      if (sceneNeedsQualifier(facility.scene)) errors.push(`Page scene depicts something brandable without a generic qualifier: ${facility.slug}`);
      if (NAMES_A_REAL_PLACE.test(facility.scene)) errors.push(`Page scene names a real venue or operator: ${facility.slug}`);
      if (!facility.alt.trim()) errors.push(`Page image needs a description: ${facility.slug}`);
      if (!imageAltSchema.safeParse(illustrativeAlt(facility.alt)).success) errors.push(`Page image description is invalid: ${facility.slug}`);
    }
  }
  return errors;
}

/**
 * A scene that puts a boat, a deck, equipment, a meal or people in frame is a
 * scene that could acquire a brand, a vessel name or a recognisable face. Those
 * must carry their own qualifier rather than relying on the shared style block.
 * An empty landscape has nothing to brand and needs none.
 */
const DEPICTS_SOMETHING_BRANDABLE = /\b(boat|yacht|speedboat|vessel|hull|deck|cabin|equipment|buffet|lunch|massage|people|figures|guest|crew|ride|window)/i;
const CARRIES_QUALIFIER = /\b(generic|unbranded|unmarked|incidental|no |nothing |without )/i;

/** Neither venue, the operator, nor any real named place may be asked for. */
const NAMES_A_REAL_PLACE = /\bhula|paradise island|paradise beach|queen magi|orange bay\b/i;

export function sceneNeedsQualifier(scene: string): boolean {
  return DEPICTS_SOMETHING_BRANDABLE.test(scene) && !CARRIES_QUALIFIER.test(scene);
}

/** The platform's disclosure convention: the storefront captions any image whose description starts with this. */
export const ILLUSTRATIVE_IMAGE_PREFIX = 'Illustrative image:';

/** A frame this script generated, told apart from a real photograph by its folder alone. */
export function isGeneratedAsset(url: string, plan: Pick<IslandImagePlan, 'urlMarker'>): boolean {
  return url.includes(plan.urlMarker);
}

/**
 * The description stored with a generated frame. It names what the frame shows,
 * in the scene's own opening words, and always declares itself illustrative.
 */
export function illustrativeAlt(description: string): string {
  const opening = description.split(/[,.;]/)[0]!.trim();
  return `${ILLUSTRATIVE_IMAGE_PREFIX} ${opening.charAt(0).toLowerCase()}${opening.slice(1)}.`;
}

const fullPrompt = (scene: string): string => `${scene} ${STYLE}`;

function argValue(name: string): string | null {
  const prefix = `--${name}=`;
  const hit = process.argv.slice(2).find((arg) => arg.startsWith(prefix));
  return hit ? hit.slice(prefix.length) : null;
}

function selectPlan(slug: string | null): IslandImagePlan {
  const plan = QUEEN_MAGI_ISLAND_IMAGE_PLANS.find((candidate) => candidate.tenantSlug === slug);
  if (!plan) {
    throw new Error(`Name the site to work on: --tenant=${QUEEN_MAGI_ISLAND_IMAGE_PLANS.map((item) => item.tenantSlug).join(' or --tenant=')}`);
  }
  return plan;
}

async function generateAndUpload(scene: string, folder: string, publicId: string, urlMarker: string): Promise<string> {
  const { base64, mimeType } = await generateImageFromPrompt({
    prompt: fullPrompt(scene),
    size: '1536x1024',
    quality: 'high',
    outputFormat: 'jpeg',
  });
  const uploaded = await uploadBase64Image(`data:${mimeType};base64,${base64}`, folder, { publicId, overwrite: true });
  if (!uploaded.url.includes(urlMarker)) throw new Error(`Upload returned an unexpected asset path for ${publicId}.`);
  return uploaded.url;
}

async function applyImagePlan(plan: IslandImagePlan): Promise<void> {
  const args = new Set(process.argv.slice(2));
  if (!args.has(`--confirm-tenant=${plan.tenantSlug}`) || !args.has('--confirm-assets=generated-only')) {
    throw new Error(`Apply fence missing. Pass --confirm-tenant=${plan.tenantSlug} and --confirm-assets=generated-only.`);
  }

  await connectDatabase();
  try {
    const tenant = await Tenant.findOne({ slug: plan.tenantSlug }).select('_id slug status designMode heroImages customPages');
    if (!tenant || tenant.status !== 'active') throw new Error(`The active ${plan.tenantSlug} site was not found.`);
    if (tenant.designMode !== plan.designMode) {
      throw new Error(`Refusing to work on a site in the wrong design: ${tenant.designMode}.`);
    }

    const targetSlugs = plan.tours.map((item) => item.slug);
    const tours = targetSlugs.length
      ? await Attraction.find({ slug: { $in: targetSlugs }, ownerTenantId: tenant._id })
        .select('_id slug status ownerTenantId tenantIds images imageAltTexts presentationRevision')
      : [];
    if (tours.length !== targetSlugs.length) {
      const found = new Set(tours.map((tour) => tour.slug));
      throw new Error(`Missing catalogue records on this site: ${targetSlugs.filter((slug) => !found.has(slug)).join(', ')}`);
    }
    for (const tour of tours) {
      const owned = String(tour.ownerTenantId) === String(tenant._id)
        && tour.tenantIds.some((tenantId) => String(tenantId) === String(tenant._id));
      if (!owned || tour.status !== 'active') throw new Error(`Refusing an image write outside this site's catalogue: ${tour.slug}.`);
      if ((tour.images || []).length > IMAGES_PER_TOUR) throw new Error(`Refusing to trim an expanded gallery on ${tour.slug}.`);
    }

    console.log(JSON.stringify({
      mode: 'pre-apply-report',
      tenant: plan.tenantSlug,
      generatedOnly: true,
      heroes: { present: (tenant.heroImages || []).length, target: plan.heroTarget },
      tours: tours.map((tour) => ({
        slug: tour.slug,
        present: tour.images.length,
        real: tour.images.filter((url) => !isGeneratedAsset(url, plan)).length,
        remaining: Math.max(0, IMAGES_PER_TOUR - tour.images.length),
      })),
      pages: plan.facilities.map((facility) => ({
        slug: facility.slug,
        hasImage: Boolean((tenant.customPages || []).find((page) => page.slug === facility.slug)?.heroImage),
      })),
    }, null, 2));

    // Tour galleries: generated frames are appended after the real photographs.
    for (const item of plan.tours) {
      const tour = tours.find((candidate) => candidate.slug === item.slug)!;
      let currentImages = [...(tour.images || [])];
      let currentAlts: ImageAltText[] = (tour.imageAltTexts || []).map((row) => ({ url: row.url, alt: row.alt }));
      let revision = tour.presentationRevision ?? 0;
      // Real photographs keep their places; the scene list is indexed from the
      // first generated frame, so a retry resumes exactly where it stopped.
      const realCount = currentImages.filter((url) => !isGeneratedAsset(url, plan)).length;
      for (let index = currentImages.length; index < IMAGES_PER_TOUR; index += 1) {
        const sceneIndex = index - realCount;
        if (sceneIndex >= item.scenes.length) {
          console.log(JSON.stringify({ slug: item.slug, stopped: 'the plan has no further scene for this gallery', filled: currentImages.length }));
          break;
        }
        const scene = item.scenes[sceneIndex]!;
        const url = await generateAndUpload(scene, plan.folder, `${item.slug}-generated-${String(sceneIndex + 1).padStart(2, '0')}`, plan.urlMarker);
        const nextImages = [...currentImages, url];
        const nextAlts = imageAltTextsSchema.parse([
          ...currentAlts.filter((row) => row.url !== url),
          { url, alt: illustrativeAlt(scene) },
        ]);
        // Same fence as the admin editor: the gallery read and its presentation
        // revision must both still hold, and the revision moves on with the write.
        const result = await Attraction.updateOne(
          {
            _id: tour._id,
            ownerTenantId: tenant._id,
            images: currentImages,
            ...(revision === 0
              ? { $or: [{ presentationRevision: 0 }, { presentationRevision: { $exists: false } }] }
              : { presentationRevision: revision }),
          },
          { $set: { images: nextImages, imageAltTexts: nextAlts }, $inc: { presentationRevision: 1 } },
        );
        if (result.modifiedCount !== 1) throw new Error(`Concurrent image edit detected on ${item.slug}; the asset was not attached.`);
        currentImages = nextImages;
        currentAlts = nextAlts;
        revision += 1;
        console.log(JSON.stringify({ slug: item.slug, image: index + 1, url }));
      }
    }

    // Facility pages: only a page with no photograph of its own is filled.
    for (const facility of plan.facilities) {
      const page = (tenant.customPages || []).find((candidate) => candidate.slug === facility.slug);
      if (!page) throw new Error(`Missing page on this site: ${facility.slug}.`);
      if (page.heroImage) {
        console.log(JSON.stringify({ page: facility.slug, skipped: 'already has an image' }));
        continue;
      }
      const url = await generateAndUpload(facility.scene, plan.folder, `page-${facility.slug}`, plan.urlMarker);
      const result = await Tenant.updateOne(
        { _id: tenant._id, slug: plan.tenantSlug, customPages: { $elemMatch: { slug: facility.slug, heroImage: { $in: [null, ''] } } } },
        { $set: { 'customPages.$.heroImage': url, 'customPages.$.heroImageAlt': imageAltSchema.parse(illustrativeAlt(facility.alt)) } },
      );
      if (result.modifiedCount !== 1) throw new Error(`Concurrent page edit detected on ${facility.slug}; the asset was not attached.`);
      console.log(JSON.stringify({ page: facility.slug, url }));
    }

    // Site headers: generated frames are appended after the real photographs.
    let heroImages = [...(tenant.heroImages || [])];
    if (heroImages.length > plan.heroTarget) throw new Error('Refusing to trim an expanded site header set.');
    const realHeroCount = heroImages.filter((url) => !isGeneratedAsset(url, plan)).length;
    for (let index = heroImages.length; index < plan.heroTarget; index += 1) {
      const sceneIndex = index - realHeroCount;
      if (sceneIndex >= plan.heroScenes.length) {
        console.log(JSON.stringify({ stopped: 'the plan has no further site header scene', filled: heroImages.length }));
        break;
      }
      const scene = plan.heroScenes[sceneIndex];
      const url = await generateAndUpload(scene, plan.folder, `hero-generated-${String(sceneIndex + 1).padStart(2, '0')}`, plan.urlMarker);
      const next = [...heroImages, url];
      const result = await Tenant.updateOne(
        { _id: tenant._id, slug: plan.tenantSlug, heroImages },
        { $set: { heroImages: next } },
      );
      if (result.modifiedCount !== 1) throw new Error('Concurrent site header edit detected; the asset was not attached.');
      heroImages = next;
      console.log(JSON.stringify({ hero: index + 1, url }));
    }

    const refreshed = await Attraction.find({ slug: { $in: targetSlugs }, ownerTenantId: tenant._id }).select('slug images');
    // A gallery is complete when it holds every frame the plan can supply, which
    // is the target unless the plan simply has fewer scenes than the gap.
    const short = refreshed.filter((tour) => {
      const item = plan.tours.find((candidate) => candidate.slug === tour.slug)!;
      const real = tour.images.filter((url) => !isGeneratedAsset(url, plan)).length;
      return tour.images.length < Math.min(IMAGES_PER_TOUR, real + item.scenes.length);
    });
    if (short.length) throw new Error(`Post-apply image check failed: ${short.map((tour) => tour.slug).join(', ')}`);

    console.log(JSON.stringify({
      mode: 'applied',
      tenant: plan.tenantSlug,
      generatedOnly: true,
      tours: refreshed.length,
      images: refreshed.reduce((sum, tour) => sum + tour.images.length, 0),
      generated: refreshed.reduce((sum, tour) => sum + tour.images.filter((url) => isGeneratedAsset(url, plan)).length, 0),
      siteHeaders: heroImages.length,
      safeguards: [
        'no real photograph replaced and no gallery trimmed',
        'every frame generic, unbranded and never presented as the venue',
        'every write a compare-and-set against the value read',
      ],
    }, null, 2));
  } finally {
    await disconnectDatabase();
  }
}

export async function main(): Promise<void> {
  const errors = validateIslandImagePlan();
  if (errors.length) throw new Error(`Image plan is invalid:\n- ${errors.join('\n- ')}`);

  const plan = selectPlan(argValue('tenant') || argValue('confirm-tenant'));
  if (!new Set(process.argv.slice(2)).has('--apply')) {
    console.log(JSON.stringify({
      mode: 'dry-run',
      tenant: plan.tenantSlug,
      designMode: plan.designMode,
      generatedOnly: true,
      folder: `attractions-network/${plan.folder}`,
      siteHeaders: { target: plan.heroTarget, scenes: plan.heroScenes.length },
      galleryTarget: IMAGES_PER_TOUR,
      tours: plan.tours.map((item) => ({ slug: item.slug, scenes: item.scenes.length })),
      pages: plan.facilities.map((item) => item.slug),
      safeguards: [
        'no database connection',
        'no image generation',
        'no upload',
        'no real photograph replaced',
        'no source, marketplace or competitor imagery',
      ],
    }, null, 2));
    return;
  }
  await applyImagePlan(plan);
}

if (require.main === module) {
  main().catch((error) => {
    console.error(`[queen-magi-island-images] ${error instanceof Error ? error.message : String(error)}`);
    process.exitCode = 1;
  });
}
