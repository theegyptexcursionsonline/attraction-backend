/**
 * Fill the photography gaps on the two Queen Magi island sites with original
 * generated illustration, and only where a real photograph does not exist.
 *
 * Both venues sit on Big Giftun off Hurghada. One of them has a recovered set
 * of its own photographs; the other has almost none. This script never invents
 * a picture of a real place: every scene is a generic Red Sea island day, with
 * no brand, no vessel name, no legible text, no logo and no identifiable
 * person, and the result is never presented as a photograph of the venue. It
 * exists so a site can be reviewed and shown before the professional shoot,
 * and so each generated asset is tracked and replaceable.
 *
 * Real imagery always wins. Generated images are appended after whatever real
 * photographs a record already carries, are never used to replace one, and a
 * gallery is never trimmed. A facility page keeps any hero image it already
 * has. Every write is a compare-and-set against the exact value read, so a
 * retry resumes after the last asset that was persisted and two runs can never
 * double up.
 *
 * Generated frames live in their own `generated/` folder under the site's tour
 * assets. The seeds mirror the real photographs into `tours/<site>/<tour>/`, so
 * the folder is the only reliable way to tell the two apart. Every generated
 * gallery frame also gets an image description that starts "Illustrative
 * image:", the platform's disclosure convention, so the storefront can caption
 * it; a generated page hero gets the same prefix on its description.
 *
 * Images are generated by gpt-image-1.5 through the platform image service.
 *
 * Dry run (no database, image API or upload connection):
 *   npm run images:queen-magi-islands -- --tenant=hula-hula-island
 * Apply in the backend service environment:
 *   npm run images:queen-magi-islands -- --apply --confirm-tenant=hula-hula-island --confirm-assets=generated-only
 */

